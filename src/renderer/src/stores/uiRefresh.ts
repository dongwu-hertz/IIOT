/**
 * 顶栏那颗**唯一的**刷新按钮与当前页面之间的那条线（业主 2026-09-19 更正第 4 条：
 * 「每个子页面里面的单独刷新按钮都应该删除」）。
 *
 * WHY THIS EXISTS AT ALL
 * 在那之前每个页面自己画一颗「刷新」：告警记录、事件中心、历史趋势、样本库、设备详情、
 * 系统设置各一颗，加上顶栏那一颗 —— 同一件事有七颗按钮，而它们刷新的是七个不同的读数。
 * 业主把页面里那几颗删掉之后，**重读当前页面数据的能力必须还在**，否则"删掉重复按钮"
 * 就变成了"删掉刷新这个功能"：那几页只在挂载与筛选变化时读一次库，看完一眼想再看一次
 * 就只能离开这一页再回来。
 *
 * HOW IT WORKS（以及为什么不更花哨）
 * 一个自增的计数器，顶栏刷新时 +1，页面 `watch` 它并按自己的方式重读。没有事件总线、
 * 没有按页面注册回调：那种做法要在卸载时注销，而漏掉一次注销就是一片"看不见的泄漏"，
 * 这个仓库已经因为同类问题吃过亏（见 `MonitorView` 的文件头）。计数器只有一个数字，
 * 页面卸载时 watch 自动失效，**没有需要手动清理的东西**。
 *
 * WHY THE PINIA STORE AND NOT A MODULE-LEVEL REF
 * 与 `stores/` 里其它状态一致：它需要被两个不相关的组件（顶栏 + 任意页面）共享，
 * 而且要在热更新与测试里可重置。生命周期比"一次进程"短、比"一个组件"长，正好是 store。
 */

import { defineStore } from 'pinia'
import { ref } from 'vue'

export const useUiRefreshStore = defineStore('uiRefresh', () => {
  /**
   * 每按一次顶栏刷新 +1。
   *
   * 只增不减：它是个"第几次刷新"的序号，页面只需要知道"变了"，不需要知道是第几次。
   */
  const tick = ref(0)

  /** 时间戳，给顶栏那句「上次刷新 <时间>」用（原来就在 `AppTopbar` 里）。 */
  function bump(): void {
    tick.value += 1
  }

  return { tick, bump }
})
