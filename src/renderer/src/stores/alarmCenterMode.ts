/**
 * 「告警中心这一屏正在看着」——一个只有两个动作的会话级状态。
 *
 * ---------------------------------------------------------------------------
 * 为什么需要它（业主 2026-09-26 第 5 条）
 * ---------------------------------------------------------------------------
 * 原话：「告警中心中应该支持非告警弹窗的问题」。
 *
 * 现状与它要挡的东西（读了 shell 与联动两处之后认定的）：
 *
 *   1. **真正的告警提示**：一条新的未确认告警到达 → 响一次（`AppShell` 的
 *      `watch(linkage.pending)`）。这一条**不能挡** —— 它在任何页面上都该响，
 *      操作员正是为了"有事要你知道"才开着这个软件。
 *   2. **持续的催办**：只要还有未确认告警，每 4 秒重复响一次
 *      （`AppShell` 的 `watch(linkage.unacknowledgedCount)`）。
 *      这一条在**告警中心这一屏上是多余的**：那一页的中心就是一整幅宽的告警详情，
 *      告警本身就在眼前。它在这里响只是"同一个事实的第二个提醒"。
 *   3. **非告警类的弹窗/提示**：系统消息（认证失败、存储不可写…）与联动动作结果
 *      （录像成功/失败…）这类**不是告警**的东西，在告警中心里同样不该再响一次：
 *      操作员已经在处理告警了。
 *
 * 所以这个 store 只回答一个问题：**告警中心现在是不是屏幕上这一页**。由它决定
 * 「第 2、3 类要不要让路」这件事的判据只有一处，而不是散在几个组件里各写一遍
 * `route.path === '/alarms'`（那是同一件事的第二份实现，改路由时必漏一处）。
 *
 * ---------------------------------------------------------------------------
 * 它不是什么
 * ---------------------------------------------------------------------------
 *   · 它**不关掉铃铛角标** —— 数字一直都在（"有几条没看"与"要不要再响一次"是两件事）；
 *   · 它**不清空任何列表** —— 本文件一个字节的数据都不改，只表达"当前这一屏是哪一页"；
 *   · 它**不拦截主进程那个置顶弹窗窗口**。那个窗口由主进程的联动动作创建
 *     （`linkage-actions.ts` 的 `ElectronPopupSink`），渲染层没有关它的 IPC，
 *     硬加一条通道会连"弹窗自己关掉时确认那条告警"的行为一起改 —— 超出这一条要求。
 *     这一段的边界写在 `docs/UI-VERIFY.md` 对应那一轮里，不当作已实现。
 */
import { computed, ref } from 'vue'
import { defineStore } from 'pinia'

/** 告警中心的路由路径（与 `router/index.ts` 里那一条必须一致）。 */
export const ALARM_CENTER_PATH = '/alarms'

export const useAlarmCenterModeStore = defineStore('alarmCenterMode', () => {
  const onScreen = ref(false)

  /**
   * 持续催办与非告警通知要不要发声。
   *
   * 读起来是"能不能打扰"，不是"要不要显示"：告警本身照样进列表、角标照样跳数字，
   * 只是**不再额外响一次**。
   */
  const quietForNotifications = computed(() => onScreen.value)

  /** 进入告警中心时调用（`AlarmsView` 挂载 / 路由确认落在这一页时）。 */
  function enter(): void {
    onScreen.value = true
  }

  /** 离开时调用（`onUnmounted`）。视图卸载就是"这一屏不在了"的权威判据。 */
  function leave(): void {
    onScreen.value = false
  }

  return { onScreen, quietForNotifications, enter, leave }
})
