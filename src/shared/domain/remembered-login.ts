/**
 * 「记住密码」的有效期策略（纯函数，零依赖）。
 *
 * ---------------------------------------------------------------------------
 * 产品要求（业主 2026-09-16）
 * ---------------------------------------------------------------------------
 *   1. 记住上次的用户名；
 *   2. 用户**勾选了**「记住密码」才记住密码；
 *   3. **每三个月**重新输入一次密码。
 *
 * ---------------------------------------------------------------------------
 * 第 3 条里最容易做错的一处：自动填充的登录**不许**续期
 * ---------------------------------------------------------------------------
 * 如果每次登录成功都把「记住时间」刷新成现在，那么第 3 条永远不会发生：登录页自动填好密码、
 * 用户点一下登录、时间被刷新，再过三个月还是这样。用户永远不需要重新输入 —— 而"每三个月
 * 重新输入一次"这句话的全部意义就是这个。
 *
 * 所以刷新**只有一个触发条件：这一次的密码是用户自己敲进去的**（`userTypedPassword`）。
 * 自动填充的那次登录会沿用原来的记住时间，于是时间一到就真的过期。
 *
 * 时间基准是「用户最后一次**亲手输入**这个密码的时刻」，不是"最后一次登录" —— 这一点写在
 * 这里，因为它是这两个时间戳容易混淆的地方。
 */

/** 记住密码的有效期：三个月按 90 天算（不是"三个自然月"，那会让边界随月份长度漂移）。 */
export const REMEMBERED_PASSWORD_MAX_AGE_MS = 90 * 24 * 60 * 60 * 1000

/**
 * 记住的那个密码现在还能不能用。
 *
 * `rememberedAt` 缺失（从没记过、或已被清除）时返回 `false` —— "没有记录"与"过期"对调用方
 * 是同一件事（都要用户重新输入），但两者在对外的说法上不同，所以调用方拿到的结果里会分开。
 *
 * 边界取**闭区间**：正好第 90 天的那一刻仍然可用，过了才失效。这样"三个月"是完整的三个月，
 * 不会因为毫秒取整少一点点。
 */
export function isRememberedPasswordUsable(
  rememberedAt: number | undefined,
  now: number
): boolean {
  if (rememberedAt === undefined || !Number.isFinite(rememberedAt)) return false
  if (!Number.isFinite(now)) return false
  // 时钟被往回调（改了系统时间、或 NTP 修正）时，`now < rememberedAt`。这**不是**"还早得很"，
  // 而是一个不可信的输入：宁可要求重新输入，也不要凭空延长有效期。
  if (now < rememberedAt) return false
  return now - rememberedAt <= REMEMBERED_PASSWORD_MAX_AGE_MS
}

/**
 * 这次的记住时间该写成什么。
 *
 * - 用户**亲手输入**了密码 ⇒ 写 `now`，开一个新的 90 天窗口；
 * - 密码是自动填充的 ⇒ 沿用 `previous`（**不续期**，见文件头那段）；
 * - 从来没有过记住时间、而这次又是自动填充（理论上的组合：读取时被判过期就不会自动填充）
 *   ⇒ 返回 `undefined`：没有可沿用的时间就不假装有。
 */
export function nextRememberedAt(
  previous: number | undefined,
  now: number,
  userTypedPassword: boolean
): number | undefined {
  if (userTypedPassword) return now
  return previous
}
