/**
 * FA371 声学相机**固件升级**的领域模型。
 *
 * 契约链（规格 §7 / 附录 C 规则 2）：
 *   设备响应  ->  主进程服务  ->  [本文件]  ->  渲染层
 *
 * 硬规则：本文件**不放人类可读文案**，只放事实与稳定的 KEY，渲染层用
 * `cameraUpgradeUi.*` 去翻译；也不出现任何线上键名（那是主进程服务与 DTO 的事）。
 *
 * ---------------------------------------------------------------------------
 * 与 `camera-control.ts` 的分工
 * ---------------------------------------------------------------------------
 * `camera-control.ts` 管「检测能不能跑起来」以及那张**维护能力表**
 * （升级/回滚/重启/恢复出厂各自可不可用）。本文件管的是**一个升级包从本机到设备**
 * 这条链路上的事实：包的名字/大小/校验和、上传结果、上传进度、重启结果。
 * 两者刻意不合并：能力表回答「界面上该不该出现这个控件」，而这里回答
 * 「这个包是什么、这台设备收下了没有」。
 *
 * ---------------------------------------------------------------------------
 * 为什么这套东西现在有了（背景，改动前先读）
 * ---------------------------------------------------------------------------
 * 先前这一项是**刻意不做**的：厂家给的升级流程是 SSH/SFTP + 自解压脚本
 * （`docs/reference/fe128-upgrade-procedure.txt`），不适合做进桌面软件。
 * 现在确认**设备自带 Web 界面那条路**是纯 HTTP，可以照做：
 *
 *   POST /upload    multipart/form-data，两个段（一个**空字段名** + 一个 `file`），
 *                   设备自带前端把超时设成 1800 秒
 *   PUT  /reboot    重启设备（`en('/reboot')` 是 PUT；`Qt` 才是 GET，不是同一个 helper）
 *   GET  /progress  升级进度
 *
 * 三个接口都是从设备自带前端的 bundle（`/static/js/main.<hash>.js`）里读出来的，
 * **不在任何一份手册里**，所以每一个都以「实测/未文档化接口」对待：
 * 读不到就如实说不懂，拿不准的地方绝不编一个数字。
 */

// ---------------------------------------------------------------------------
// 升级包文件名规则（**设备自己**的规则，逐字照抄）
// ---------------------------------------------------------------------------

/**
 * 设备自带前端对升级包文件名的判定：
 *
 * ```js
 * var ext = f[0].name.split('_').pop().toLowerCase()
 * if (!/^[Vv]\d+\.\d+\.\d+$/.test(ext)) return msg.error('Please upload the correct upgrade package file')
 * ```
 *
 * 也就是说：**文件名按 `_` 切开后的最后一段**必须是 `V<数字>.<数字>.<数字>`。
 * 例：`FE128_ROBOT_PLUS_upgrade_pkg_RK3568_v2.0.11` 的最后一段是 `v2.0.11`，通过；
 * `..._v2.0`、`..._2.0.11`、`package.zip` 都不通过。
 *
 * 这条规则值得在**上传之前**复核：包是按几十 MB 计的，让设备读完之后才拒绝，
 * 等于把一次长上传白白用完再报错。
 */
export const CAMERA_UPGRADE_SUFFIX_PATTERN = /^[Vv]\d+\.\d+\.\d+$/

/**
 * 文件名按设备的方式取出的「后缀」：最后一个 `_` 之后的那一段。
 *
 * 没有下划线时整名即是那一段（`package.zip` → `package.zip`），这与浏览器里
 * `split('_').pop()` 的行为一致。路径分隔符先剥掉：设备拿到的是文件名，
 * 不是路径。
 */
export function cameraUpgradeSuffix(fileName: string): string {
  const base = fileName.split(/[\\/]/).pop() ?? fileName
  return base.split('_').pop() ?? ''
}

/**
 * 这个文件名设备会不会收（本地预判，与设备同一条规则）。
 *
 * 设备是先取最后一段再 `toLowerCase()` 再匹配，这里照做而不是直接给正则加 `i`：
 * 两者的判定结果相同，但把「设备真的做了什么」留在代码里，日后设备改规则时
 * 对照的是同一段逻辑。
 */
export function isAcceptableCameraUpgradePackageName(fileName: string): boolean {
  return CAMERA_UPGRADE_SUFFIX_PATTERN.test(cameraUpgradeSuffix(fileName).toLowerCase())
}

// ---------------------------------------------------------------------------
// 包在本机的静态事实
// ---------------------------------------------------------------------------

/**
 * 一个升级包在**本机**的事实（这一步不碰设备）。
 *
 * `sha256` 的用途是「与厂家发布的校验值核对」：升级包是那种"传错了也叫成功、
 * 结果设备刷成砖"的文件，所以在按下上传之前，操作员要能拿一个本机算出来的
 * 指纹去比对。它不是设备要求的字段（设备只要 `{"file_size":N}`），是本软件加的。
 */
export interface CameraUpgradePackage {
  /** 绝对路径（主进程选出来的；渲染层只用于显示与回传）。 */
  path: string
  /** 基础文件名（含扩展名）。 */
  fileName: string
  /** 字节数。 */
  sizeBytes: number
  /** 小写十六进制 sha256。 */
  sha256: string
  /** 文件名最后一段（设备规则判定用的就是它）。 */
  suffix: string
  /** 文件名是否符合设备自己的规则（`false` 时界面必须拒绝上传）。 */
  nameAccepted: boolean
}

// ---------------------------------------------------------------------------
// 上传
// ---------------------------------------------------------------------------

/**
 * 一次上传的结果。
 *
 * **这里没有任何「升级完成」的含义**：设备自带前端在 `POST /upload` 返回 200 之后
 * 才去 `PUT /reboot`，也就是说上传只把包放进设备，**重启才开始升级**。所以本类型
 * 只说明「包被收下了」，重启是另一个显式动作（见 `CameraRebootResult`）。
 */
export interface CameraUpgradeUploadResult {
  deviceId: string
  fileName: string
  sizeBytes: number
  /** 本机算出的 sha256，与 `CameraUpgradePackage.sha256` 同一个值。 */
  sha256: string
  /** 设备回的 HTTP 状态码（设备自带前端以 `200 === res.status` 判成功）。 */
  status: number
  /** 从请求发出到设备应答的耗时（ms）。 */
  elapsedMs: number
  /** 设备应答正文的前若干字节（诊断用；通常是 `{"msg":...}` 或空）。 */
  responseSnippet?: string
}

/**
 * 上传进度（主进程 -> 渲染层的推送）。
 *
 * 推的是**真实写出的请求体字节数**：`HttpTransport` 那条路一次性把响应读完，
 * 拿不到中途的字节数（见 `EventDownloadProgress` 的说明），所以升级这条链
 * 特意走 `node:http` 流式上传，进度才有真实来源。`sentBytes` 含 multipart 的
 * 边界与元数据段，因此与 `totalBytes` 同量纲；`packageBytes` 是操作员认得的那个
 * 数字（包本身的字节数）。
 */
export interface CameraUpgradeProgressEvent {
  deviceId: string
  /** 已写出的请求体字节数（含边界与元数据段）。 */
  sentBytes: number
  /** 请求体总字节数。 */
  totalBytes: number
  /** 升级包本身的字节数。 */
  packageBytes: number
  /** `round(100 * sentBytes / totalBytes)`，由主进程算好，界面不做算术。 */
  percent: number
}

// ---------------------------------------------------------------------------
// 设备侧升级进度（`GET /progress`）
// ---------------------------------------------------------------------------

/**
 * 设备自报的升级进度。
 *
 * ⚠ **`upgrade_progress` 的量纲与取值含义没有文档。** 真机只读实测
 * （`192.168.110.235`，`V0.5.1.6_251219`）空闲时返回 `-2.0`：
 *
 * ```
 * GET /progress -> 200 {"msg":"SUCCESS","ret":200,"upgrade_progress":-2.0}
 * ```
 *
 * 一个"看不懂的数字"不该被渲染成进度条，所以这里**只交出设备原样的数值**，
 * 由界面连同「该值含义设备没有文档」一起显示。要换算成百分比，先得有厂商说明。
 */
export interface CameraUpgradeProgress {
  /** 设备原样返回的 `upgrade_progress`；设备没回这个字段时缺省。 */
  raw?: number
  /** 设备原样返回的 `msg`（诊断用）。 */
  deviceMessage?: string
}

// ---------------------------------------------------------------------------
// 重启（`PUT /reboot`）
// ---------------------------------------------------------------------------

/**
 * 一次重启请求的结果。
 *
 * 与上传**分开成两个动作**是这一项最要紧的约束：升级包上传完不会自动重启，
 * 由操作员显式点一次。因此这里如实区分两件事：
 *
 *   - `acknowledged` —— 设备回了 2xx，收到了明确的应答；
 *   - `connectionDropped` —— 请求已经发出，但设备在应答之前就断开了。
 *
 * 第二种在重启时是**常见的形状**（设备要重启，socket 先断），把它报成失败会
 * 让操作员以为没发出去而再点一次 —— 所以它单独一个字段，界面据此说
 * 「指令已发出，设备未回执」，而不是「重启失败」。
 */
export interface CameraRebootResult {
  deviceId: string
  /** 设备回了 2xx。 */
  acknowledged: boolean
  /** 请求发出后连接断开、没有拿到应答（重启时的常见形状，不是"没发出去"）。 */
  connectionDropped: boolean
}
